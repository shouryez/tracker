const seen = new Set();
for (const [name] of COLLEGES) {
  const key = name.toLowerCase();
  if (seen.has(key)) throw new Error(`Duplicate college: ${name}`);
  seen.add(key);
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const sql = `-- Starter list of colleges for the onboarding picker (${COLLEGES.length} entries).
-- Generated by scripts/gen-college-seed.mjs. Students can add missing colleges
-- during onboarding. Safe to re-run.
INSERT INTO "colleges" ("name", "short_name", "city", "state")
SELECT v.name, v.short_name, v.city, v.state
FROM (VALUES
${COLLEGES.map((c) => `  (${c.map(q).join(", ")})`).join(",\n")}
) AS v(name, short_name, city, state)
WHERE NOT EXISTS (SELECT 1 FROM "colleges" c WHERE lower(c."name") = lower(v.name));
`;

writeFileSync(new URL("../drizzle/0003_seed_colleges.sql", import.meta.url), sql);
